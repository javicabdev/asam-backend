// Generate creates n random cash movements, inserting them in batches.
func (g *CashflowGenerator) Generate(ctx context.Context, n int) error {
	if n <= 0 {
		return nil // Nothing to generate
	}

	var members []MemberIDInfo
	err := g.db.SelectContext(ctx, &members, "SELECT id FROM members WHERE state = $1", models.EstadoActivo)
	if err != nil {
		return fmt.Errorf("failed to get active members: %w", err)
	}
	// It's okay if len(members) is 0: kinds that require a member are skipped.
	kinds := g.availableKinds(len(members) > 0)

	tx, err := g.db.BeginTxx(ctx, nil)
	if err != nil {
		return fmt.Errorf("failed to begin transaction: %w", err)
	}
	// Defer rollback. It will be executed if an error occurs or if Commit is not called.
	defer func(txToRollback *sqlx.Tx) {
		// Attempt to rollback. This is a cleanup action.
		// The primary error (if any) from the main function body is more important.
		if rollbackErr := txToRollback.Rollback(); rollbackErr != nil && !errors.Is(rollbackErr, sql.ErrTxDone) {
			// Log the rollback error if it's not sql.ErrTxDone (which means Commit or another Rollback already happened)
			log.Printf("Error during deferred transaction rollback: %v", rollbackErr)
		}
	}(tx)

	batchSize := 100 // Optimal batch size can vary
	for i := 0; i < n; i += batchSize {
		itemsInThisBatch := batchSize
		if i+batchSize > n {
			itemsInThisBatch = n - i
		}

		if err := g.generateAndInsertBatch(ctx, tx, kinds, members, itemsInThisBatch); err != nil {
			// No need to explicitly call Rollback here, the defer will handle it.
			return fmt.Errorf("failed to generate or insert cashflow batch: %w", err)
		}
	}

	// If all batches succeeded, commit the transaction.
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("failed to commit transaction: %w", err)
	}
	return nil
}

// availableKinds returns the kinds that can be generated given whether there are active members.
func (g *CashflowGenerator) availableKinds(haveMembers bool) []cashflowKind {
	if haveMembers {
		return g.kinds
	}
	kinds := make([]cashflowKind, 0, len(g.kinds))
	for _, k := range g.kinds {
		if !k.requiresMember {
			kinds = append(kinds, k)
		}
	}
	return kinds
}

// pickKind selects a kind at random, proportionally to its weight.
func (g *CashflowGenerator) pickKind(kinds []cashflowKind) cashflowKind {
	total := 0
	for _, k := range kinds {
		total += k.weight
	}
	n := g.rand.Intn(total)
	for _, k := range kinds {
		if n < k.weight {
			return k
		}
		n -= k.weight
	}
	return kinds[len(kinds)-1] // Unreachable: n < total
}

// generateSingleCashflowData creates one Cashflow data struct.
func (g *CashflowGenerator) generateSingleCashflowData(kinds []cashflowKind, members []MemberIDInfo) Cashflow {
	kind := g.pickKind(kinds)

	var memberID *int
	if len(members) > 0 && (kind.requiresMember || g.rand.Float64() < kind.memberProb) {
		id := members[g.rand.Intn(len(members))].MemberID
		memberID = &id
	}

	amount := GenerateRandomAmount(g.rand, kind.minAmount, kind.maxAmount)
	if kind.opType.IsExpense() {
		amount = -amount
	}

	// Generate date within the last 3 years
	now := time.Now()
	startDate := now.AddDate(-3, 0, 0)
	date := GenerateRandomDate(g.rand, startDate, now)

	return Cashflow{
		MemberID:      memberID,
		OperationType: string(kind.opType),
		Amount:        amount,
		Date:          date,
		Detail:        kind.details[g.rand.Intn(len(kind.details))],
	}
}

// generateAndInsertBatch generates a batch of cash movements and inserts them.
func (g *CashflowGenerator) generateAndInsertBatch(
	ctx context.Context,
	tx *sqlx.Tx,
	kinds []cashflowKind,
	members []MemberIDInfo,
	numToGenerateInBatch int,
) error {
	if numToGenerateInBatch <= 0 {
		return nil
	}

	cashflows := make([]Cashflow, 0, numToGenerateInBatch)
	for i := 0; i < numToGenerateInBatch; i++ {
		cashflowEntry := g.generateSingleCashflowData(kinds, members)
		cashflows = append(cashflows, cashflowEntry)
	}

	query := `
		INSERT INTO cash_flows (member_id, operation_type, amount, date, detail)
		VALUES (:member_id, :operation_type, :amount, :date, :detail)`

	_, err := tx.NamedExecContext(ctx, query, cashflows)
	if err != nil {
		return fmt.Errorf("failed to insert cashflow batch: %w", err)
	}
	return nil
}

// GetCashflowsByPeriod retrieves cash movements for a given period
func (g *CashflowGenerator) GetCashflowsByPeriod(ctx context.Context, startDate, endDate time.Time) ([]Cashflow, error) {
	var cashflows []Cashflow
	query := `
		SELECT id, member_id, operation_type, amount, date, detail
		FROM cash_flows
		WHERE date BETWEEN $1 AND $2
		ORDER BY date, id` // Added id for stable sort

	err := g.db.SelectContext(ctx, &cashflows, query, startDate, endDate)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) { // Use errors.Is for checking specific errors
			return []Cashflow{}, nil
		}
		return nil, fmt.Errorf("failed to get cash movements for period: %w", err)
	}
	return cashflows, nil
}

// GetCashflowsByType retrieves cash movements for a given operation type
func (g *CashflowGenerator) GetCashflowsByType(ctx context.Context, operationType models.OperationType) ([]Cashflow, error) {
	var cashflows []Cashflow
	query := `
		SELECT id, member_id, operation_type, amount, date, detail
		FROM cash_flows
		WHERE operation_type = $1
		ORDER BY date, id` // Added id for stable sort

	err := g.db.SelectContext(ctx, &cashflows, query, string(operationType))
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return []Cashflow{}, nil
		}
		return nil, fmt.Errorf("failed to get cash movements by type '%s': %w", operationType, err)
	}
	return cashflows, nil
}

