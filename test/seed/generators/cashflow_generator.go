// MemberIDInfo holds only the ID of a member.
type MemberIDInfo struct {
	MemberID int `db:"id"`
}

// cashflowKind describes how to fake movements of one domain operation type.
// The rows are inserted with raw SQL, bypassing models.CashFlow.Validate, so
// every kind must produce rows that would pass it.
type cashflowKind struct {
	opType models.OperationType
	// weight is the relative frequency of this kind among generated movements.
	weight int
	// minAmount and maxAmount bound the absolute amount; the sign comes from
	// opType (income > 0, expense < 0), as models.CashFlow.Validate requires.
	minAmount, maxAmount float64
	// requiresMember marks types that are meaningless without a member
	// (a membership fee, a repatriation). They are skipped if there are none.
	requiresMember bool
	// memberProb is the chance of linking an optional-member kind to a member.
	memberProb float64
	details    []string
}

// CashflowGenerator generates test cash movements (caja)
type CashflowGenerator struct {
	db   *sqlx.DB
	rand *rand.Rand
	// Pre-defined operation kinds for efficiency
	kinds []cashflowKind
}

// Cashflow represents a cash_flows record for generation
